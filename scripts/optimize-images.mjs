// Creates a smaller WebP copy of every large image in public/images
// (recursively, including subfolders like festivals/) and records which
// ones exist in src/constants/optimizedImages.js, so the app can serve
// the light version (see src/utils/image.js).
//
// The original PNG/JPG files are left untouched: puja/festival/pandit
// records in the database point at them, and social-media link
// previews prefer them.
//
// Run: npm run optimize:images   (safe to re-run; up to date files are skipped)

import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, extname, basename, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = fileURLToPath(new URL('..', import.meta.url));
const imagesDir = join(root, 'public', 'images');
const MIN_BYTES = 150 * 1024; // smaller images are already cheap
const MAX_WIDTH = 1600; // widest slot in the layout, at 1x
const QUALITY = 78;

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      yield* walk(full);
    } else {
      yield full;
    }
  }
}

const optimized = [];
let savedBytes = 0;

for (const source of [...walk(imagesDir)].sort()) {
  const ext = extname(source).toLowerCase();
  if (!['.png', '.jpg', '.jpeg'].includes(ext)) continue;

  const size = statSync(source).size;
  if (size < MIN_BYTES) continue;

  const target = join(source, '..', `${basename(source, ext)}.webp`);
  if (!existsSync(target) || statSync(target).mtimeMs < statSync(source).mtimeMs) {
    await sharp(source)
      .resize({ width: MAX_WIDTH, withoutEnlargement: true })
      .webp({ quality: QUALITY, effort: 5 })
      .toFile(target);
  }

  const after = statSync(target).size;
  savedBytes += size - after;
  const publicPath = `/images/${relative(imagesDir, source).split('\\').join('/')}`;
  optimized.push(publicPath);
  console.log(`${publicPath.padEnd(40)} ${(size / 1024).toFixed(0).padStart(6)} KB -> ${(after / 1024).toFixed(0).padStart(5)} KB`);
}

writeFileSync(
  join(root, 'src', 'constants', 'optimizedImages.js'),
  `// GENERATED by scripts/optimize-images.mjs - do not edit by hand.
// Original image paths that have a lighter .webp copy next to them.
export const OPTIMIZED_IMAGES = new Set(${JSON.stringify(optimized, null, 2)});
`,
);

console.log(`\n${optimized.length} images optimized, ${(savedBytes / 1024 / 1024).toFixed(1)} MB less to download.`);
