DEFAULT_CITY = "Jaipur"

_BY_KEY = {name.lower(): name for name in CITY_COORDINATES}


def locate_city(name, state=None):
    """
    (city, state, lat, lon, exact) for a city name. Unknown names fall
    back to a city in the same state, then to Jaipur (exact=False).
    """
    key = " ".join(str(name or "").split()).lower()
    if key in _BY_KEY:
        city = _BY_KEY[key]
        city_state, lat, lon = CITY_COORDINATES[city]
        return city, city_state, lat, lon, True

    wanted_state = " ".join(str(state or "").split()).lower()
    if wanted_state:
        for city, (city_state, lat, lon) in CITY_COORDINATES.items():
            if city_state.lower() == wanted_state:
                return (name or city), city_state, lat, lon, False

    city_state, lat, lon = CITY_COORDINATES[DEFAULT_CITY]
    return DEFAULT_CITY, city_state, lat, lon, False
